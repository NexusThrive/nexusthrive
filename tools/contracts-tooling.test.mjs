import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { cpSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const buf = join(root, "tools/bin/buf");

test("breaking compatibility rejects a renamed field", () => {
  const temp = mkdtempSync(join(tmpdir(), "contracts-breaking-"));
  try {
    cpSync(join(root, "contracts"), join(temp, "contracts"), { recursive: true });
    const file = join(temp, "contracts/proto/kernel/v1/kernel.proto");
    const original = readFileSync(file, "utf8");
    assert.ok(original.includes("string amount = 3;"));
    writeFileSync(file, original.replace("string amount = 3;", "string quantity = 3;"));
    assert.throws(() => execFileSync(buf, ["breaking", join(temp, "contracts"), "--against", join(root, "contracts")], { encoding: "utf8", stdio: "pipe" }), (error) => {
      assert.equal(error.status, 100);
      assert.match(`${error.stdout}${error.stderr}`, /amount|FIELD_SAME_NAME/);
      return true;
    });
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
});

// Compare every generated byte, including newly created paths, not only tracked files.
function snapshot(dir) {
  return readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? snapshot(path) : [[path, readFileSync(path, "utf8")]];
  });
}

test("a second local generation leaves every output unchanged", () => {
  const dirs = [join(root, "kernel/gen"), join(root, "packages/sdk/src/gen")];
  const before = dirs.flatMap(snapshot);
  execFileSync(process.execPath, [join(root, "tools/contracts-generate.mjs")], { cwd: root, stdio: "pipe" });
  assert.deepEqual(dirs.flatMap(snapshot), before);
});
