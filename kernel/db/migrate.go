package db

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"io/fs"
	"regexp"

	"github.com/jackc/pgx/v5"
	"github.com/pressly/goose/v3"
	"github.com/pressly/goose/v3/lock"
)

// schemaNamePattern limits schema names to plain lowercase identifiers so a
// name can never smuggle SQL into the statements built from it.
var schemaNamePattern = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

// versionTable is the goose control table; each schema keeps its own copy so
// kernel, platform and business version independently (ADR-0024).
const versionTable = "goose_db_version"

// Config selects the schema and the migration files to apply.
type Config struct {
	// Schema is validated against ^[a-z_][a-z0-9_]*$ and quoted when used.
	Schema string
	// Files holds the goose SQL files at its root; KernelMigrations by default.
	Files fs.FS
}

// Migrate creates cfg.Schema when missing and applies every pending migration
// in cfg.Files. Each file runs in its own transaction, so a failing file
// leaves no partial changes. Running it again with nothing pending is a no-op.
//
// The schema is created here, not in a migration, because the control table
// lives inside it and must exist before the first migration runs.
func Migrate(ctx context.Context, db *sql.DB, cfg Config) error {
	if !schemaNamePattern.MatchString(cfg.Schema) {
		return fmt.Errorf("migrate: invalid schema name %q", cfg.Schema)
	}
	files := cfg.Files
	if files == nil {
		files = KernelMigrations()
	}
	quoted := pgx.Identifier{cfg.Schema}.Sanitize()

	if _, err := db.ExecContext(ctx, "CREATE SCHEMA IF NOT EXISTS "+quoted); err != nil {
		return fmt.Errorf("migrate: create schema %s: %w", cfg.Schema, err)
	}

	// The advisory lock keeps concurrent deployments from racing; it needs a
	// direct or session-mode connection (ADR-0019).
	locker, err := lock.NewPostgresSessionLocker()
	if err != nil {
		return fmt.Errorf("migrate: session locker: %w", err)
	}
	provider, err := goose.NewProvider(
		goose.DialectPostgres, db, files,
		// goose parses and quotes the name itself and looks the table up by
		// plain schema name, so it gets the unquoted, already validated one.
		goose.WithTableName(cfg.Schema+"."+versionTable),
		goose.WithSessionLocker(locker),
	)
	if err != nil {
		// A schema with no files is valid; it still gets its control table.
		if errors.Is(err, goose.ErrNoMigrations) {
			return ensureVersionTable(ctx, db, quoted)
		}
		return fmt.Errorf("migrate: create provider: %w", err)
	}
	if _, err := provider.Up(ctx); err != nil {
		var failed *goose.PartialError
		if errors.As(err, &failed) && failed.Failed != nil {
			return fmt.Errorf("migrate %s: %w", failed.Failed.Source.Path, err)
		}
		return fmt.Errorf("migrate: %w", err)
	}
	return nil
}

// ensureVersionTable creates the control table for a schema without files,
// with the same shape goose uses, so the state matches a migrated schema.
func ensureVersionTable(ctx context.Context, db *sql.DB, quotedSchema string) error {
	stmt := "CREATE TABLE IF NOT EXISTS " + quotedSchema + "." + versionTable + ` (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)`
	if _, err := db.ExecContext(ctx, stmt); err != nil {
		return fmt.Errorf("migrate: create version table: %w", err)
	}
	return nil
}
